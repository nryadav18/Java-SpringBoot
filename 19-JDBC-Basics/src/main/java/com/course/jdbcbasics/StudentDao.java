package com.course.jdbcbasics;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/*
 * StudentDao.java
 * ------------------------------------------------------------
 * DAO = Data Access Object: ONE class that contains ALL the SQL for ONE table.
 * The rest of the program just calls save(), findById(), ... and never sees SQL.
 * (In Spring this idea becomes a "Repository" - Topics 37 and 38.)
 *
 * Every method follows the same JDBC recipe:
 *   1) get a Connection
 *   2) create a PreparedStatement with ? placeholders
 *   3) set the parameter values (setString, setInt, ...)
 *   4) execute: executeQuery() for SELECT, executeUpdate() for INSERT/UPDATE/DELETE
 *   5) read the ResultSet (for SELECT) and map rows -> Student objects
 *   6) close everything (try-with-resources does it for us)
 *
 * Notice how much code repeats in every method. That repetition ("boilerplate")
 * is exactly what Spring's JdbcTemplate removes.
 */
public class StudentDao {

    // ---------------- CREATE ----------------
    /** Inserts a student and returns a copy that contains the id generated by the database. */
    public Student save(Student student) throws SQLException {
        String sql = "INSERT INTO students (name, email, marks) VALUES (?, ?, ?)";

        try (Connection conn = Database.getConnection();
             // RETURN_GENERATED_KEYS: "please give me the AUTO_INCREMENT id you created"
             PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setString(1, student.name());   // 1st ?   (JDBC counts from 1, not 0!)
            ps.setString(2, student.email());  // 2nd ?
            ps.setInt(3, student.marks());     // 3rd ?

            int rows = ps.executeUpdate();     // returns how many rows were inserted
            if (rows != 1) {
                throw new SQLException("Insert failed, rows affected: " + rows);
            }

            try (ResultSet keys = ps.getGeneratedKeys()) {
                keys.next();
                int newId = keys.getInt(1);
                return new Student(newId, student.name(), student.email(), student.marks());
            }
        }
    }

    // ---------------- READ one ----------------
    /** Optional (Topic 14): the student may not exist. Spring Data's findById works the same way. */
    public Optional<Student> findById(int id) throws SQLException {
        String sql = "SELECT id, name, email, marks FROM students WHERE id = ?";

        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {                       // move the cursor to the first row (if any)
                    return Optional.of(mapRow(rs));
                }
                return Optional.empty();
            }
        }
    }

    // ---------------- READ all ----------------
    public List<Student> findAll() throws SQLException {
        String sql = "SELECT id, name, email, marks FROM students ORDER BY id";
        List<Student> result = new ArrayList<>();

        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {                        // one loop step per row
                result.add(mapRow(rs));
            }
        }
        return result;
    }

    // ---------------- READ with a condition ----------------
    public List<Student> findByMinMarks(int minMarks) throws SQLException {
        String sql = "SELECT id, name, email, marks FROM students WHERE marks >= ? ORDER BY marks DESC";
        List<Student> result = new ArrayList<>();

        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, minMarks);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    result.add(mapRow(rs));
                }
            }
        }
        return result;
    }

    // ---------------- UPDATE ----------------
    /** @return true if a row was updated, false if no student has that id */
    public boolean updateMarks(int id, int newMarks) throws SQLException {
        String sql = "UPDATE students SET marks = ? WHERE id = ?";

        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, newMarks);
            ps.setInt(2, id);
            return ps.executeUpdate() == 1;
        }
    }

    // ---------------- DELETE ----------------
    public boolean deleteById(int id) throws SQLException {
        String sql = "DELETE FROM students WHERE id = ?";

        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, id);
            return ps.executeUpdate() == 1;
        }
    }

    // ---------------- COUNT ----------------
    public int count() throws SQLException {
        try (Connection conn = Database.getConnection();
             PreparedStatement ps = conn.prepareStatement("SELECT COUNT(*) FROM students");
             ResultSet rs = ps.executeQuery()) {
            rs.next();
            return rs.getInt(1);                       // first column of the only row
        }
    }

    // ---------------- Row mapper ----------------
    /** Turns the CURRENT row of the ResultSet into a Student. Spring calls this idea a RowMapper. */
    private Student mapRow(ResultSet rs) throws SQLException {
        return new Student(
                rs.getInt("id"),          // read by column NAME (clearer than by index)
                rs.getString("name"),
                rs.getString("email"),
                rs.getInt("marks"));
    }
}
