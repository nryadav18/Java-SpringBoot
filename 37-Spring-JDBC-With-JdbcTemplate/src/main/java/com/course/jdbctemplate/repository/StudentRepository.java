package com.course.jdbctemplate.repository;

import com.course.jdbctemplate.model.CourseStats;
import com.course.jdbctemplate.model.Student;

import java.util.List;
import java.util.Optional;

/*
 * StudentRepository - the contract (topic 33: depend on an interface).
 *
 * This project has THREE implementations of it, so you can compare the APIs:
 *   JdbcTemplateStudentRepository     - classic JdbcTemplate, "?" placeholders
 *   NamedParameterStudentRepository   - NamedParameterJdbcTemplate, ":name" placeholders
 *   JdbcClientStudentRepository       - JdbcClient, the modern fluent API (Spring 6.1+)
 *
 * Exactly ONE is active, chosen by the property app.repository.type
 * (see application.properties). The service never knows which one it gets.
 */
public interface StudentRepository {

    List<Student> findAll();

    Optional<Student> findById(long id);

    List<Student> findByCourse(String course);

    /** Inserts a new student and returns it WITH the id generated by the database. */
    Student save(Student student);

    /** Returns true if a row was updated, false if no student has this id. */
    boolean update(Student student);

    /** Returns true if a row was deleted. */
    boolean deleteById(long id);

    long count();

    List<CourseStats> courseStatistics();
}
