-- schema.sql - runs automatically at startup (BEFORE data.sql).
-- Creates the table(s). DROP first so it can safely run more than once.

DROP TABLE IF EXISTS student;

CREATE TABLE student (
    -- The database generates the id (1, 2, 3, ...).
    -- (In MySQL you would write: id BIGINT AUTO_INCREMENT PRIMARY KEY)
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,   -- no two students with the same email
    course      VARCHAR(50)  NOT NULL,
    marks       INT          NOT NULL CHECK (marks BETWEEN 0 AND 100),
    enrolled_on DATE         NOT NULL
);
